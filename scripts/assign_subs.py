CONJ = re.compile(r"[与和及、,，·的及]")

def split_words(s):
    return [w for w in CONJ.split(s) if len(w) >= 2]

def sub_score(tag, sub):
    if tag == sub:
        return 100
    if tag in sub or sub in tag:
        return 80
    tw, sw = split_words(tag), split_words(sub)
    common = [w for w in tw if w in sw]
    if common:
        return 10 * len(common)
    return 0

def assign(q, children):
    text = (q.get("stem", "") + " " + q.get("answer", "") + " " + q.get("explanation", "")).lower()
    scores = collections.Counter()
    for s in children:
        if s.lower() in text:
            scores[s] += 5
        for w in split_words(s):
            if len(w) >= 2 and w.lower() in text:
                scores[s] += 2
    for tag in TAGS:
        if tag.lower() in text:
            best, bs = None, 0
            for s in children:
                sc = sub_score(tag, s)
                if sc > bs:
                    best, bs = s, sc
            if best:
                scores[best] += 8
    for rx, feats in PATTERNS:
        if re.search(rx, text):
            for feat in feats:
                hit = next((s for s in children if feat in s), None)
                if hit:
                    scores[hit] += 8
                    break
    if scores:
        return scores.most_common(1)[0][0], sum(scores.values())
    return None, 0

def main():
    cur = json.load(open(ROOT + r"\data\curriculum.json", encoding="utf-8"))
    qs = json.load(open(ROOT + r"\data\questions.json", encoding="utf-8"))
    submap = {}
    for pid, p in cur.items():
        for c in p["chapters"]:
            submap[(pid, c["name"])] = c.get("children") or []
    unassigned = []
    for q in qs:
        children = submap.get((q["project"], q["chapter"]), [])
        if not children:
            q["sub"] = ""
            continue
        sub, score = assign(q, children)
        if not sub:
            unassigned.append((q["id"], q["project"], q["chapter"], q["stem"][:36]))
            q["sub"] = children[0]
        else:
            q["sub"] = sub
    json.dump(qs, open(ROOT + r"\data\questions.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("总题数:", len(qs))
