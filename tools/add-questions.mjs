const ids = new Set(questions.map((q) => q.id));
const added = [];
for (const item of BATCH) {
  if (ids.has(item.id)) continue;
  const project = curriculum[item.project];
  const chapter = project && project.chapters.find((c) => c.name === item.chapter);
  if (!chapter) throw new Error(`章节不存在：${item.project}/${item.chapter}`);
  if (!(chapter.children || []).includes(item.sub)) throw new Error(`小节不存在：${item.sub}`);
  if (item.type === "choice" && (!Array.isArray(item.options) || !item.options.includes(item.answer))) {
    throw new Error(`选项不含答案：${item.id}`);
  }
  questions.push(item);
  added.push(item.id);
  ids.add(item.id);
}

const byProject = questions.reduce((m, q) => ((m[q.project] = (m[q.project] || 0) + 1), m), {});
console.log(`新增 ${added.length} 道：${added.join(", ") || "无"}`);
console.log("各科题量：", byProject);
console.log("解答题总数：", questions.filter((q) => q.type === "essay").length);

if (!dry) {
  writeFileSync(FILE, `${JSON.stringify(questions, null, 1)}\n`, "utf8");
  console.log(`已写回 ${FILE}`);
}
